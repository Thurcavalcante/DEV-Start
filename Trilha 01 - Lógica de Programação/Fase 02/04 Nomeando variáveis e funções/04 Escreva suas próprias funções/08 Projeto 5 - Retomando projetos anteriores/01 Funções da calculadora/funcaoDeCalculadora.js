// Defina as quatro funções aqui
function soma(primeiroValor, segundoValor) {
  return primeiroValor + segundoValor;
}

function subtrai(primeiroValor, segundoValor) {
  return primeiroValor - segundoValor;
}

function multiplica(primeiroValor, segundoValor) {
  return primeiroValor * segundoValor;
}

function divide(primeiroValor, segundoValor) {
  return primeiroValor / segundoValor;
}
